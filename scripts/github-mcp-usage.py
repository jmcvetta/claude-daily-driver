#!/usr/bin/env python3
"""Count which GitHub MCP tools were actually called, and roll them up to toolsets.

This exists to answer one question with evidence instead of taste: the GitHub
MCP server offers 22 toolsets and 89 tools, every enabled tool costs context in
every session, and `--toolsets` is the only lever. Guessing the list is how you
end up carrying `stargazers` for a year and discovering, the first time a CI
skill is written, that `actions` was never enabled.

So: run everything for a fortnight, then run this. It reads Claude Code session
transcripts, counts `mcp__github__*` tool calls, maps each to the toolset that
supplies it, and prints the `--toolsets` line the observed calls justify along
with what it saves. See docs/github-mcp.md for the standing decision and the
reasoning behind it.

It also counts `gh` invocations, because the demotion of `gh` to a laptop-only
escape hatch is a claim with the same shape: residual `gh` use is the list of
things the MCP did not do, and it is worth reading rather than assuming.

Usage:

    python3 scripts/github-mcp-usage.py                    # all transcripts
    python3 scripts/github-mcp-usage.py --since 2026-09-06 # the fortnight
    python3 scripts/github-mcp-usage.py --projects DIR     # a non-default root

No third-party imports, for the same reason as check-manifests.py: this runs
from a Makefile on a laptop, and a dependency install is a place for two runs
to differ.
"""

