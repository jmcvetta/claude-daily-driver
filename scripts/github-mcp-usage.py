# The server's own `default` — what you get by setting no toolsets at all.
# Named here so the recommendation can say whether narrowing beats doing
# nothing, which for a PR-and-issues workflow it very nearly does not.
#
# Derived by diffing `tools/list` under `default` against each toolset, not
# read off the README. Note that `get_label` belongs to both `issues` and
# `labels`, so `default` contains a `labels` tool without enabling `labels`;
# taking the toolset list from the tools alone would wrongly add it.
DEFAULT_TOOLSETS = frozenset(
    {"context", "copilot", "issues", "pull_requests", "repos", "users"}
)

MCP_PREFIX = "mcp__github__"

# A leading `VAR=value` does not stop `gh` from being in command position.
ASSIGNMENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*=")

# `<<EOF`, `<<-EOF`, `<<'EOF'`, `<<"EOF"` — enough to find where a heredoc
# body starts, so its contents are not read as commands.
HEREDOC = re.compile(r"<<-?\s*(?:'([^']*)'|\"([^\"]*)\"|([A-Za-z_][A-Za-z0-9_]*))")


def transcripts(root: Path):
    """Every transcript under a Claude Code projects directory.

    Recursive rather than `*/*.jsonl`: a session's subagent transcripts live
    at `<project>/<session>/subagents/*.jsonl`, and their tool calls are tool
    calls. A toolset reached for only from subagents would otherwise be absent
    from the recommendation.
    """
    return sorted(root.rglob("*.jsonl"))


def tool_uses(path: Path, since: str | None):
    """Yield (tool name, input dict) for each tool call recorded in a transcript.

    Transcript records are one JSON object per line; an assistant turn carries
    its tool calls as `tool_use` blocks in `message.content`. A malformed or
    truncated line is skipped rather than fatal — a transcript being written
    by a live session will have one.
    """
    with path.open(encoding="utf-8", errors="replace") as handle:
        for line in handle:
            try:
                record = json.loads(line)
            except (json.JSONDecodeError, ValueError):
                continue
            if not isinstance(record, dict):
                continue
            if since and (record.get("timestamp") or "") < since:
                continue
            content = (record.get("message") or {}).get("content")
            if not isinstance(content, list):
                continue
            for block in content:
                if isinstance(block, dict) and block.get("type") == "tool_use":
                    yield block.get("name") or "", block.get("input") or {}


OPERATORS = {"|", "||", "&&", ";", ";;", "&", "(", ")", "{", "}", "then", "do", "else", "env"}
SUBCOMMAND = re.compile(r"^[a-z][a-z-]*$")


def command_lines(command: str):
    """The lines of a shell command, with heredoc bodies dropped.

    A heredoc body is data, not commands, so `gh api` written inside one is
    not a use of `gh`. Finding where the body ends needs only the delimiter.
    """
    lines = command.splitlines()
    index = 0
    while index < len(lines):
        line = lines[index]
        index += 1
        yield line
        match = HEREDOC.search(line)
        if not match:
            continue
        delimiter = next(group for group in match.groups() if group is not None)
        while index < len(lines) and lines[index].strip() != delimiter:
            index += 1
        index += 1  # the terminator itself


def words_of(line: str) -> list[str]:
    """A shell line's words, with operators as tokens of their own.

    `shlex.split` leaves punctuation attached — `cd /repo; gh pr list` splits
    to `['cd', '/repo;', 'gh', ...]`, which hides that `gh` is in command
    position. `punctuation_chars` is what separates them.
    """
    lexer = shlex.shlex(line, posix=True, punctuation_chars=True)
    lexer.whitespace_split = True
    try:
        return list(lexer)
    except ValueError:
        return line.split()


def gh_subcommands(command: str) -> list[str]:
    """Every `gh` subcommand a shell command line invokes, in order.

    Deliberately shallow, and only counts `gh` in command position — at the
    start of a line or after a shell operator — so `command -v gh` and a
    `gh api` written inside a heredoc do not register as uses. Every command
    position counts, not just the first: `gh pr list && gh issue list` is two
    uses of two different subcommands. Two words of subcommand are kept,
    making `gh pr create` and `gh run watch` distinct rows while
    `gh api /repos/...` collapses to `gh api`.

    This is a tally of what `gh` is still reached for, not a parser, and it is
    a live demonstration of D2's point: recognising a command in a shell
    string is guesswork, which is exactly why the hook that enforces MCP use
    matches an MCP tool name instead.
    """
    found: list[str] = []
    for line in command_lines(command):
        words = words_of(line)
        for index, word in enumerate(words):
            if word != "gh":
                continue
            previous = words[index - 1] if index else None
            if (
                previous is not None
                and previous not in OPERATORS
                and not ASSIGNMENT.match(previous)
            ):
                continue
            rest: list[str] = []
            for candidate in words[index + 1 :]:
                if not SUBCOMMAND.match(candidate) or len(rest) == 2:
                    break
                rest.append(candidate)
            found.append(" ".join(["gh", *rest]) if rest else "gh")
    return found


def report(mcp: Counter, gh: Counter, unknown: Counter, transcript_count: int) -> None:
    print(f"transcripts read: {transcript_count}")

    print("\nGitHub MCP tools called")
    if not mcp:
        print("  (none)")
    for name, count in mcp.most_common():
        print(f"  {count:5d}  {name}  [{TOOLS[name][0]}]")

    if unknown:
        print("\nCalled but absent from this script's table — regenerate it")
        for name, count in unknown.most_common():
            print(f"  {count:5d}  {name}")

    # Resolve each called tool to one toolset. Only `get_label` has a choice
    # to make, and crediting both of its toolsets would recommend enabling
    # `labels` for a tool that `issues` already supplies — so tools with a
    # single home are settled first, and an ambiguous tool then takes a
    # toolset already required rather than adding one.
    used: set[str] = set()
    ambiguous: list[tuple[str, int]] = []
    per_toolset: Counter = Counter()
    for name, count in mcp.items():
        toolsets = TOOLS[name][0].split(",")
        if len(toolsets) == 1:
            used.add(toolsets[0])
            per_toolset[toolsets[0]] += count
        else:
            ambiguous.append((name, count))
    for name, count in ambiguous:
        toolsets = TOOLS[name][0].split(",")
        chosen = next((t for t in toolsets if t in used), toolsets[0])
        used.add(chosen)
        per_toolset[chosen] += count

    print("\nBy toolset")
    for toolset, count in per_toolset.most_common():
        print(f"  {count:5d}  {toolset}")

    everything = sum(size for _, size in TOOLS.values())
    kept = sum(
        size
        for toolsets, size in TOOLS.values()
        if used.intersection(toolsets.split(","))
    )
    default = sum(
        size
        for toolsets, size in TOOLS.values()
        if DEFAULT_TOOLSETS.intersection(toolsets.split(","))
    )

    print("\nWhat the calls justify")
    if unknown:
        # The table is stale, so `used` is a floor: a tool it does not know
        # may be the only call into a toolset the line below omits. Say so
        # here rather than beside the unknown tools, where a reader copying
        # the flag has already scrolled past it.
        print(f"  INCOMPLETE — {len(unknown)} called tool(s) are missing from this")
        print("  script's table (listed above), so the line below may omit a")
        print("  toolset. Regenerate the table before acting on it.")
    if not used:
        print("  nothing known was called; the measurement has not run long enough")
    else:
        print(f"  --toolsets {','.join(sorted(used))}")
        print(f"  {len(used)} of {len({t for s, _ in TOOLS.values() for t in s.split(',')})} toolsets")
        print(f"  {kept:,} chars of tool definitions, against {everything:,} for `all`")
        print(f"  and {default:,} for the server's own `default`")
        if used <= DEFAULT_TOOLSETS and kept >= default * 0.9:
            print("  — barely under `default`; setting no toolsets at all is close enough")

    print("\n`gh` invocations (what the MCP did not do)")
    if not gh:
        print("  (none)")
    for name, count in gh.most_common():
        print(f"  {count:5d}  {name}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--projects",
        type=Path,
        default=Path.home() / ".claude" / "projects",
        help="Claude Code projects directory (default: ~/.claude/projects)",
    )
    parser.add_argument(
        "--since",
        default=None,
        help="ignore records before this ISO-8601 instant, e.g. 2026-09-06",
    )
    args = parser.parse_args()

    if not args.projects.is_dir():
        print(f"no such directory: {args.projects}", file=sys.stderr)
        return 1

    mcp: Counter = Counter()
    gh: Counter = Counter()
    unknown: Counter = Counter()
    paths = transcripts(args.projects)

    for path in paths:
        for name, payload in tool_uses(path, args.since):
            if name.startswith(MCP_PREFIX):
                tool = name[len(MCP_PREFIX) :]
                (mcp if tool in TOOLS else unknown)[tool] += 1
            elif name == "Bash":
                for subcommand in gh_subcommands(str(payload.get("command") or "")):
                    gh[subcommand] += 1

    report(mcp, gh, unknown, len(paths))
    return 0


if __name__ == "__main__":
    sys.exit(main())
